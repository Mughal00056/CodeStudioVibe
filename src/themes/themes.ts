export function resolveTheme(themeId: ThemeId, customThemes: IDETheme[]): IDETheme {
  if (themeId in BUILT_IN_THEMES) {
    return BUILT_IN_THEMES[themeId as BuiltInThemeId];
  }
  const custom = customThemes.find((t) => t.id === themeId);
  return custom || BUILT_IN_THEMES.dark;
}
